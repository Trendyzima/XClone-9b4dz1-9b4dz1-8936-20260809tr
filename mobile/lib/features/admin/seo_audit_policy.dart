enum SeoRouteStatus { good, warn, missing, noindex }

class SeoRouteContract {
  const SeoRouteContract(
      {required this.path,
      required this.label,
      required this.group,
      required this.hasUseSeo,
      required this.hasStructuredData,
      required this.noindex});
  final String path;
  final String label;
  final String group;
  final bool hasUseSeo;
  final bool hasStructuredData;
  final bool noindex;

  SeoRouteStatus get status {
    if (noindex) {
      return SeoRouteStatus.noindex;
    }
    if (!hasUseSeo) {
      return group == 'Dynamic' ? SeoRouteStatus.missing : SeoRouteStatus.warn;
    }
    if (hasStructuredData) {
      return SeoRouteStatus.good;
    }
    return SeoRouteStatus.warn;
  }
}

